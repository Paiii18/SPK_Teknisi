    private void loadTableTeknisi() {

        DefaultTableModel model
                = new DefaultTableModel();

        model.addColumn("ID");
        model.addColumn("Kode");
        model.addColumn("Nama");
        model.addColumn("Jenis Kelamin");
        model.addColumn("No Telepon");
        model.addColumn("Divisi");
        model.addColumn("Jabatan");
        model.addColumn("Status");

        TeknisiDAO dao = new TeknisiDAO();

        for (model.Teknisi t : dao.getAll()) {

            model.addRow(new Object[]{
                t.getIdTeknisi(),
                t.getKodeTeknisi(),
                t.getNamaTeknisi(),
                t.getJenisKelamin(),
                t.getNoTelepon(),
                t.getDivisi(),
                t.getJabatan(),
                t.getStatus()
            });
        }

        tblteknisi.setModel(model);
    }

    private void generateKodeTeknisi() {

        TeknisiDAO dao = new TeknisiDAO();

        String kode = dao.generateKode();

        tkodeteknisi.setText(kode);
    }

    private void cariTeknisi(String keyword) {

        DefaultTableModel model
                = new DefaultTableModel();

        model.addColumn("ID");
        model.addColumn("Kode");
        model.addColumn("Nama");
        model.addColumn("Jenis Kelamin");
        model.addColumn("No Telepon");
        model.addColumn("Divisi");
        model.addColumn("Jabatan");
        model.addColumn("Status");

        TeknisiDAO dao = new TeknisiDAO();

        for (model.Teknisi t : dao.search(keyword)) {

            model.addRow(new Object[]{
                t.getIdTeknisi(),
                t.getKodeTeknisi(),
                t.getNamaTeknisi(),
                t.getJenisKelamin(),
                t.getNoTelepon(),
                t.getDivisi(),
                t.getJabatan(),
                t.getStatus()
            });
        }

        tblteknisi.setModel(model);
    }

