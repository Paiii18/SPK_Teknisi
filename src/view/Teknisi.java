    private void btnhapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnhapusActionPerformed
        String kode
                = tkodeteknisi.getText().trim();

        if (kode.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Pilih data terlebih dahulu");

            return;
        }

        int konfirmasi
                = JOptionPane.showConfirmDialog(
                        this,
                        "Yakin ingin menghapus Teknisi Dengan Kode "
                        + kode + "?",
                        "Konfirmasi Hapus",
                        JOptionPane.YES_NO_OPTION);

        if (konfirmasi == JOptionPane.YES_OPTION) {

            TeknisiDAO dao = new TeknisiDAO();

            if (dao.delete(kode)) {

                JOptionPane.showMessageDialog(
                        this,
                        "Data berhasil dihapus");

                loadTableTeknisi();

                resetForm();

            } else {

                JOptionPane.showMessageDialog(
                        this,
                        "Data gagal dihapus");
            }
        }
    }//GEN-LAST:event_btnhapusActionPerformed

    private void btneditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btneditActionPerformed
        if (tkodeteknisi.getText().trim().isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Pilih data terlebih dahulu dari tabel");

            return;
        }

        model.Teknisi t = new model.Teknisi();

        t.setKodeTeknisi(
                tkodeteknisi.getText().trim());

        t.setNamaTeknisi(
                tnamateknisi.getText().trim());

        t.setJenisKelamin(
                tjeniskelamin.getSelectedItem().toString());

        t.setTempatLahir(
                ttempatlahir.getText().trim());

        t.setTanggalLahir(
                ttanggallahir.getDate() != null
                ? new java.sql.Date(
                        ttanggallahir.getDate().getTime())
                : null);

        t.setAlamat(
                talamat.getText().trim());

        t.setNoTelepon(
                tnotelp.getText().trim());

        t.setEmail(
                temail.getText().trim());

        t.setDivisi(
                tdivisi.getText().trim());

        t.setJabatan(
                tjabatan.getSelectedItem().toString());

        t.setTanggalMasuk(
                ttanggalmasuk.getDate() != null
                ? new java.sql.Date(
                        ttanggallahir.getDate().getTime())
                : null);

        t.setStatus(
                tstatus.getSelectedItem().toString());

        TeknisiDAO dao = new TeknisiDAO();

        if (dao.update(t)) {

            JOptionPane.showMessageDialog(
                    this,
                    "Data teknisi berhasil diupdate");

            loadTableTeknisi();

            resetForm();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Data teknisi gagal diupdate");
        }
    }//GEN-LAST:event_btneditActionPerformed

