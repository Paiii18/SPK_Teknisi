    private void btnsimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsimpanActionPerformed
        if (tkodeteknisi.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Kode Teknisi tidak boleh kosong");
            return;
        }

        if (tnamateknisi.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Nama Teknisi tidak boleh kosong");
            return;
        }

        model.Teknisi t = new model.Teknisi();

        t.setKodeTeknisi(tkodeteknisi.getText().trim());

        t.setNamaTeknisi(tnamateknisi.getText().trim());

        t.setJenisKelamin(tjeniskelamin.getSelectedItem().toString());

        t.setTempatLahir(ttempatlahir.getText().trim());

        t.setTanggalLahir(
                ttanggallahir.getDate() != null
                ? new java.sql.Date(
                        ttanggallahir.getDate().getTime())
                : null);

        t.setAlamat(talamat.getText().trim());

        t.setNoTelepon(tnotelp.getText().trim());

        t.setEmail(temail.getText().trim());

        t.setDivisi(tdivisi.getText().trim());

        t.setJabatan(tjabatan.getSelectedItem().toString());

        t.setTanggalMasuk(
                ttanggalmasuk.getDate() != null
                ? new java.sql.Date(
                        ttanggalmasuk.getDate().getTime())
                : null);

        t.setStatus(tstatus.getSelectedItem().toString());

        TeknisiDAO dao = new TeknisiDAO();

        if (dao.insert(t)) {

            JOptionPane.showMessageDialog(
                    this,
                    "Data Teknisi Berhasil Disimpan");

            resetForm();
            loadTableTeknisi();
            generateKodeTeknisi();
        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Data Teknisi Gagal Disimpan");
        }
    }//GEN-LAST:event_btnsimpanActionPerformed

    private void tblteknisiMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblteknisiMouseClicked
        int row = tblteknisi.getSelectedRow();

        if (row == -1) {
            return;
        }

        String kode
                = tblteknisi.getValueAt(row, 1).toString();

        TeknisiDAO dao
                = new TeknisiDAO();

        model.Teknisi t
                = dao.getByKode(kode);

        if (t != null) {

            tkodeteknisi.setText(
                    t.getKodeTeknisi());

            tnamateknisi.setText(
                    t.getNamaTeknisi());

            tjeniskelamin.setSelectedItem(
                    t.getJenisKelamin());

            ttempatlahir.setText(
                    t.getTempatLahir());

            ttanggallahir.setDate(
                    t.getTanggalLahir());

            talamat.setText(
                    t.getAlamat());

            tnotelp.setText(
                    t.getNoTelepon());

            temail.setText(
                    t.getEmail());

            tdivisi.setText(
                    t.getDivisi());

            tjabatan.setSelectedItem(
                    t.getJabatan());

            ttanggalmasuk.setDate(
                    t.getTanggalMasuk());

            tstatus.setSelectedItem(
                    t.getStatus());
        }
        btnsimpan.setVisible(false);
    }//GEN-LAST:event_tblteknisiMouseClicked

